return {
	"folke/snacks.nvim",
	priority = 1000,
	lazy = false,
	opts = {
		bigfile = { enabled = true },
		indent = { enabled = true },
		input = { enabled = true },
		lazygit = { enabled = true },
		notifier = { enabled = true },
		picker = { enabled = true },
	},
	-- stylua: ignore
	keys = {
		{ "<leader>sh", function() Snacks.picker.help() end, desc = "[S]earch [H]elp" },
		{ "<leader>sk", function() Snacks.picker.keymaps() end, desc = "[S]earch [K]eymaps" },
		{ "<leader>sf", function() Snacks.picker.files() end, desc = "[S]earch [F]iles" },
		{ "<leader>ss", function() Snacks.picker.pickers() end, desc = "[S]earch [S]elect picker" },
		{ "<leader>sw", function() Snacks.picker.grep_word() end, desc = "[S]earch current [W]ord", mode = { "n", "x" } },
		{ "<leader>sg", function() Snacks.picker.grep() end, desc = "[S]earch by [G]rep" },
		{ "<leader>sd", function() Snacks.picker.diagnostics() end, desc = "[S]earch [D]iagnostics" },
		{ "<leader>sr", function() Snacks.picker.resume() end, desc = "[S]earch [R]esume" },
		{ "<leader>s.", function() Snacks.picker.recent() end, desc = "[S]earch recent files" },
		{ "<leader>s/", function() Snacks.picker.grep_buffers() end, desc = "[S]earch [/] in open files" },
		{ "<leader>sn", function() Snacks.picker.files({ cwd = vim.fn.stdpath("config"), follow = true }) end, desc = "[S]earch [N]eovim files" },
		{ "<leader><leader>", function() Snacks.picker.buffers() end, desc = "[ ] Find existing buffers" },
		{ "<leader>/", function() Snacks.picker.lines() end, desc = "[/] Search in current buffer" },
		{ "<leader>gg", function() Snacks.lazygit() end, desc = "Lazy[g]it" },
		{ "<leader>gl", function() Snacks.lazygit.log_file() end, desc = "Lazygit [l]og for current file" },
	},
}
